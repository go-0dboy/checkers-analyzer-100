/* разбор строки ходов: отбрасываем номера ходов, "x"/"-" — разделитель */
function tokenize(s: string): [number, number][] {
  const out: [number, number][] = [];
  for (const raw of s.trim().split(/\s+/)) {
    const t = raw.replace(/^\d+\.?/, '');
    const m = /^(\d{1,2})[xX×\-–—](\d{1,2})$/.exec(t);
    if (m) out.push([Number(m[1]), Number(m[2])]);
  }
  return out;
}

interface BookEntry { from: number; to: number; weight: number; name: string }

const BOOK = new Map<string, Map<number, BookEntry>>();

for (const line of LINES) {
  let pos: Pos = { b: startBoard(), side: WHITE };
  for (const [from, to] of tokenize(line.moves)) {
    const m = findMove(generateMoves(pos), from, to);
    if (!m) break; /* ход некорректен/нелегален — обрываем линию (книга не портится) */
    const key = boardToFen(pos.b, pos.side);
    let inner = BOOK.get(key);
    if (!inner) { inner = new Map(); BOOK.set(key, inner); }
    const code = from * 100 + to;
    const ex = inner.get(code);
    if (ex) ex.weight++;
    else inner.set(code, { from, to, weight: 1, name: line.name });
    pos = applyMove(pos, m);
  }
}

/** Поиск по позиции (FEN). Возвращает ходы, отсортированные по весу. */
export function bookLookup(fen: string): BookHit | null {
  const inner = BOOK.get(fen);
  if (!inner || inner.size === 0) return null;
  const moves = [...inner.values()]
    .sort((a, b) => b.weight - a.weight)
    .map(({ from, to, weight }) => ({ from, to, weight }));
  return { name: [...inner.values()][0].name, moves };
}

