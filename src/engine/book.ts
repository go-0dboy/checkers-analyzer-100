/* ============================================================
 * Дебютная книга: короткие проверенные линии классических
 * начал. Ключ — последовательность ходов от начальной позиции.
 * Применение валидируется по легальным ходам, поэтому
 * случайный мусор в книге не способен сломать партию.
 * ============================================================ */

export interface BookHit { from: number; to: number; name: string }

interface BookLine { name: string; seq: string[] }

/* Линии записаны парами «от-куда» в нотации 1–50 (x и - не важны,
 * ключ нормализуется к «from-to»). */
const LINES: BookLine[] = [
  {
    name: 'Классическое начало',
    seq: ['32-28', '19-23', '28x19', '14x23', '37-32', '10-14', '41-37', '5-10',
      '46-41', '14-19', '34-29', '23x34', '40x29', '20-24', '29x20', '15x24',
      '44-40', '10-14', '50-44', '14-20', '40-34', '20-25', '44-40'],
  },
  {
    name: 'Старая партия',
    seq: ['32-28', '18-23', '37-32', '12-18', '41-37', '7-12', '46-41', '1-7',
      '34-30', '20-25', '30-24', '19x30', '35x24', '10-15', '31-27', '15-20'],
  },
  {
    name: 'Городская партия',
    seq: ['32-28', '18-23', '34-30', '23x32', '37x28', '20-25', '31-27', '25x34', '40x29'],
  },
  {
    name: 'Отказанный косяк',
    seq: ['33-28', '18-23', '39-33', '12-18', '44-39', '7-12', '31-27', '20-25', '37-31'],
  },
  {
    name: 'Ленинградская защита',
    seq: ['33-29', '17-21', '39-33', '11-17', '44-39', '6-11', '31-26', '18-23', '29x18', '13x22'],
  },
  {
    name: 'Обратный косяк',
    seq: ['33-29', '20-25', '38-33', '14-20', '42-38', '10-14', '47-42', '5-10', '32-28'],
  },
];

const norm = (mv: string) => {
  const [a, b] = mv.replace(/[x×X\-–—]/g, ' ').trim().split(/\s+/).map(Number);
  return `${a}-${b}`;
};

/** карта «ключ-префикс» → { следующий ход, название дебюта } */
const BOOK = new Map<string, { move: [number, number]; name: string }>();
for (const line of LINES) {
  const s = line.seq.map(norm);
  for (let i = 0; i < s.length; i++) {
    const key = s.slice(0, i).join(',');
    const [a, b] = s[i].split('-').map(Number);
    BOOK.set(key, { move: [a, b], name: line.name });
  }
}

/**
 * history — пары from*100+to всех ходов от начальной позиции.
 * Возвращает книжный ход, если вся история совпала с линией.
 */
export function bookLookup(history: number[]): BookHit | null {
  const key = history.map((c) => `${Math.floor(c / 100)}-${c % 100}`).join(',');
  const e = BOOK.get(key);
  return e ? { from: e.move[0], to: e.move[1], name: e.name } : null;
}
